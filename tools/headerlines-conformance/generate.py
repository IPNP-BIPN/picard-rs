#!/usr/bin/env python3
"""Generate `crates/picard-analysis/src/tool_options.rs` from the header-lines golden.

The command line Picard records for a `NAME=value` invocation is built from the legacy parser's
option table: which options a tool declares, in which order, with which default string, whether
each is a collection and what its element type makes of a typed value. Hand-writing that for 54
tools is neither cheap nor checkable, and reading it off the source gets the defaults wrong
whenever a default is an expression. So the table is the `decl` and `positional` rows of the golden,
which `HeaderLinesDump` reads off the parser itself, and the conformance test beside it checks the
line built from this table against the line Picard built, case by case.

    python3 tools/headerlines-conformance/generate.py           # write the module
    python3 tools/headerlines-conformance/generate.py --check   # fail if it is stale
"""

import argparse
import gzip
import pathlib
import sys

REPO = pathlib.Path(__file__).resolve().parents[2]
GOLDEN = REPO / "crates/picard-analysis/tests/data/header_lines.txt.gz"
OUT = REPO / "crates/picard-analysis/src/tool_options.rs"

HEADER = '''//! The legacy parser's option table for every tool that records its command line.
//!
//! Generated by `tools/headerlines-conformance/generate.py` from the `decl` and `positional` rows
//! of `tests/data/header_lines.txt.gz`, which `HeaderLinesDump` reads off Picard 3.5.0's own
//! `LegacyCommandLineArgumentParser`. Do not edit by hand.

/// What an option's type makes of a typed value, as far as its `toString()` shows.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Kind {
    /// Printed as typed: `String`, an enum (`Enum.valueOf` takes the exact name), a path.
    Text,
    /// `java.io.File`, which normalises its slashes.
    File,
    /// `Integer`, `Long`, `Short`, `Byte`: parsed, so a sign or leading zeros go.
    Integer,
    /// `Double`, printed by `Double.toString`.
    Double,
    /// `Float`, printed by `Float.toString`.
    Float,
    /// `Boolean`, which is `parseBoolean`.
    Boolean,
}

/// How a collection orders and deduplicates what it holds, from the class of its default.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Order {
    /// A list: every value, in the order added.
    List,
    /// A `HashSet` of strings: no duplicates, in `java.util.HashMap` bucket order.
    Hash,
    /// A `LinkedHashSet`, or a `HashSet` of enum constants, whose Java order is their identity
    /// hashes and so not reproducible: no duplicates, in the order added.
    Linked,
    /// A `TreeSet`: no duplicates, sorted.
    Tree,
    /// An `EnumSet`: no duplicates, in the constants' declaration order.
    Enum,
}

/// One option, as the legacy parser holds it.
#[derive(Clone, Copy, Debug)]
pub struct OptionDecl {
    /// The upper-cased long name, which is what the line prints.
    pub name: &'static str,
    /// The upper-cased short name, or empty.
    pub short: &'static str,
    pub collection: bool,
    /// For a collection, how it orders its elements; `List` otherwise.
    pub order: Order,
    pub kind: Kind,
    /// An enum's constants in declaration order, for an `EnumSet`; empty otherwise.
    pub constants: &'static [&'static str],
    pub optional: bool,
    /// The default rendered at construction; `null` for none and for an empty collection.
    pub default: &'static str,
}

/// A tool's options in the parser's order, and the element kind of its positional arguments.
#[derive(Debug)]
pub struct ToolOptions {
    pub name: &'static str,
    pub options: &'static [OptionDecl],
    pub positional: Option<Kind>,
}

'''

KINDS = {
    "java.lang.Boolean": "Boolean",
    "java.lang.Integer": "Integer",
    "java.lang.Long": "Integer",
    "java.lang.Short": "Integer",
    "java.lang.Byte": "Integer",
    "java.lang.Double": "Double",
    "java.lang.Float": "Float",
    "java.io.File": "File",
}


JAVA_LANG = {"java.lang.String", *KINDS}


def order_of(klass, type_name):
    """A collection's order from the class of its default instance."""
    if klass.endswith("EnumSet"):
        return "Enum"
    if klass == "java.util.TreeSet":
        return "Tree"
    if klass == "java.util.LinkedHashSet":
        return "Linked"
    if klass == "java.util.HashSet":
        # `String.hashCode` is reproducible; an enum constant's is its identity hash.
        return "Hash" if type_name in JAVA_LANG else "Linked"
    return "List"


def unescape(payload):
    out, i = [], 0
    while i < len(payload):
        c = payload[i]
        if c == "\\" and i + 1 < len(payload):
            nxt = payload[i + 1]
            out.append({"t": "\t", "n": "\n", "\\": "\\"}.get(nxt, "\\" + nxt))
            i += 2
            continue
        out.append(c)
        i += 1
    return "".join(out)


def rust_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def generate(text):
    tools = {}
    positional = {}
    for line in text.splitlines():
        kind, _, rest = line.partition("\t")
        case, _, payload = rest.partition("\t")
        if kind == "decl":
            tool, _, index = case.partition("/")
            fields = unescape(payload).split("\t")
            tools.setdefault(tool, []).append((int(index), fields))
        elif kind == "positional":
            positional[case] = unescape(payload).split("\t")[0]
    out = [HEADER, "pub static TOOLS: &[ToolOptions] = &[\n"]
    for tool in sorted(tools):
        out.append("    ToolOptions {\n")
        out.append(f"        name: {rust_str(tool)},\n")
        out.append("        options: &[\n")
        for _, (name, short, collection, type_name, optional, default, klass, constants) in sorted(
            tools[tool]
        ):
            order = order_of(klass, type_name)
            names = ", ".join(rust_str(c) for c in constants.split(",")) if order == "Enum" else ""
            out.append(
                "            OptionDecl { "
                f"name: {rust_str(name)}, short: {rust_str(short)}, "
                f"collection: {collection}, order: Order::{order}, "
                f"kind: Kind::{KINDS.get(type_name, 'Text')}, constants: &[{names}], "
                f"optional: {optional}, default: {rust_str(default)} }},\n"
            )
        out.append("        ],\n")
        if tool in positional:
            out.append(f"        positional: Some(Kind::{KINDS.get(positional[tool], 'Text')}),\n")
        else:
            out.append("        positional: None,\n")
        out.append("    },\n")
    out.append("];\n")
    return "".join(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--golden", default=str(GOLDEN))
    args = ap.parse_args()
    with gzip.open(args.golden, "rt", encoding="utf-8") as fh:
        module = generate(fh.read())
    if args.check:
        if OUT.read_text() != module:
            sys.exit(f"{OUT} is stale: run tools/headerlines-conformance/generate.py")
        print(f"{OUT.name} matches the golden")
        return
    OUT.write_text(module)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
