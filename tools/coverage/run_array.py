#!/usr/bin/env python3
"""Run a covering array against the oracle, and optionally against the port.

The arrays under `tools/coverage/arrays/` are generated by gatk-rs's `tools/coverage/covering.py`
from the pinned inventory; they are rows of argument assignments and nothing more. This turns each
row into a command line, runs it, and records what came back.

Two modes, and the difference matters:

* **oracle only** (the default) produces a corpus: one row per array row, in the same dump format
  every conformance suite uses, so the result can be committed and compared like any other golden.
  It also answers a question nothing else does: which rows the reference *rejects*, and how many
  distinct outputs the argument surface actually produces. An argument that changes nothing on this
  corpus is an argument the corpus cannot test, and that is worth knowing before a port is measured
  against it.

* **with `--port`**, each row also runs the port binary and the two outputs are compared. The
  result is a coverage measurement, not a bug list: today's binaries take three arguments and
  ignore the rest (they exist for the benchmark), so a row that varies a fourth argument is
  *expected* to diverge. The number that comes out is how much of the argument surface the port
  implements, which is precisely the figure the programme has never had.

    python3 tools/coverage/run_array.py --tool CollectAlignmentSummaryMetrics
    python3 tools/coverage/run_array.py --tool CollectAlignmentSummaryMetrics \\
        --port target/release/collect-alignment-summary-metrics
"""

import argparse
import hashlib
import json
import shutil
import subprocess
import sys
import tempfile
import zlib
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "conformance"))
import compare as comparator  # noqa: E402

REPO = Path(__file__).resolve().parents[2]
ARRAYS = REPO / "tools" / "coverage" / "arrays"
IMAGE = "picard-rs-oracle:3.4.0"
PLATFORM = "linux/amd64"

# Values that mean "the argument is absent", so a held-at value carrying one must not be passed.
ABSENT = {"None", "null", "[]", ""}


def build_fixtures(workdir):
    """Materialize the corpus with MakeFixtures.java, inside the pinned container."""
    fixtures = workdir / "fixtures"
    fixtures.mkdir(parents=True, exist_ok=True)
    command = (
        'cp /harness/MakeFixtures.java . && javac -cp "$ORACLE_CP" -d . MakeFixtures.java '
        # The fixture must be byte-reproducible, so the JDK deflater is pinned here exactly as the
        # oracle contract pins it for goldens.
        '&& java -Dsamjdk.try_use_intel_deflater=false -cp ".:$ORACLE_CP" MakeFixtures /out '
        # The oracle mounts this directory read-only, so a tool that asks whether its input is
        # writable is told no; the port runs on the host, where the same files are writable, and
        # the two would disagree for a reason that is the harness's rather than the tool's.
        # `BamFileIoUtils.reheaderBamFile` calls `IOUtil.assertFileIsWritable(inputFile)` before it
        # copies anything, so every BAM row of ReplaceSamHeader is that refusal.
        #
        # The write bit comes off here, inside the container, rather than from the runner: the
        # files are written by the container as root, and on a CI runner the unprivileged user that
        # started it cannot chmod them. Only the files: the directory keeps its write bit so the
        # temporary tree can still be removed.
        "&& find /out -type f -exec chmod a-w {} +"
    )
    result = subprocess.run(
        [
            "docker", "run", "--rm", "--platform", PLATFORM,
            "-v", f"{REPO}/tools/coverage:/harness:ro",
            "-v", f"{fixtures}:/out",
            "-w", "/work", IMAGE, command,
        ],
        capture_output=True,
        text=True,
    )
    if result.returncode != 0:
        print(result.stdout[-2000:])
        print(result.stderr[-2000:])
        raise SystemExit("could not build the fixtures")

    return fixtures


def row_arguments(row, held):
    """The row's own assignments, plus the fixture values it cannot run without.

    An argument excluded with `source: "fixture"` (`--INPUT`, `--OUTPUT`, `--REFERENCE_SEQUENCE`)
    has no default, so the row must carry it. An argument excluded with `source: "default"` is
    omitted: passing a default back is at best redundant and at worst wrong, and it was wrong here.
    The first run of CollectAlignmentSummaryMetrics rejected all sixteen rows because
    `--ADAPTER_SEQUENCE`'s default is a `List[String]` and came back as a single token with its
    brackets and commas, which the parser read as positional arguments.
    """
    args = list(row["arguments"])
    covered = {a.split("=", 1)[0] for a in args}
    for entry in held:
        name, value = entry["argument"], entry.get("held_at")
        if entry.get("source") != "fixture" or name in covered:
            continue
        if value is None or str(value) in ABSENT:
            continue
        args.append(f"{name}={value}")
    return args


def as_cli(args):
    """Barclay long form: `--NAME value`, which is the syntax the claim is defined against."""
    out = []
    for pair in args:
        name, _, value = pair.partition("=")
        out += [name, value]
    return out


def fresh_directory(workdir, stem):
    """A directory no previous row has written into, for this row's output.

    Emptying one directory and reusing it looks equivalent and is not. The oracle runs in a
    container with this directory bind-mounted; deleting a file from the host and then creating a
    file of the same name from inside a later container fails on the shared mount with
    `NoSuchFileException`, and htsjdk reports that as `SAMException: Not creating BAM index`. Two
    FixMateInformation rows were recorded as that rejection, which is the harness's answer and not
    the reference's: run either row on its own and the reference writes the index and the file.

    A row therefore gets a directory of its own. They accumulate inside the run's temporary tree,
    which is removed when the run ends.
    """
    parent = workdir / stem
    parent.mkdir(exist_ok=True)
    made = parent / str(len(list(parent.iterdir())))
    made.mkdir()
    return made


def run_oracle(tool, row_args, workdir, on_stdout=False, strip_pg=False):
    """Run one row in the container. Returns (exit code, output text, stdout tail).

    `on_stdout` is for the tools that HAVE no output argument: `ViewSam` and `BamIndexStats` print
    to standard output and write no file at all. Comparing the output directory for those compares
    nothing -- every accepted row looks alike, the array reports one distinct output, and the port
    matches by producing the same nothing. That is not a measurement, and this is the difference
    between covering an argument and observing it.
    """
    out_dir = fresh_directory(workdir, "out")

    cli = " ".join(as_cli(row_args))
    # `java -jar picard.jar <Tool> <args>`: the tool name is the first token, and the arguments
    # follow in Barclay long form.
    command = f"mkdir -p /work/tmp /work/out && java -jar $PICARD_JAR {tool} {cli}"
    result = subprocess.run(
        [
            "docker", "run", "--rm", "--platform", PLATFORM,
            "-v", f"{workdir / 'fixtures'}:/work/fixtures:ro",
            "-v", f"{out_dir}:/work/out",
            "-w", "/work", IMAGE, command,
        ],
        capture_output=True,
        text=True,
    )
    text = result.stdout if on_stdout else read_output(out_dir, strip_pg)
    return result.returncode, text, first_error(result.stderr or result.stdout)


def read_output(out_dir, strip_program_records=False):
    """The row's output file, as text where it is text and as a digest where it is not.

    A record-transform writes a BAM, which is gzip, so reading it as UTF-8 throws on its second
    byte. Hashing it keeps such a tool measurable: what the comparison needs is whether the two
    sides produced the same bytes, and for a binary output the digest answers that exactly. It is
    a weaker artefact than the text corpus, because a divergence shows as two digests rather than
    as a diff, so the corpus says which it is.

    A BGZF file is hashed DECOMPRESSED. The reference deflates through Intel's GKL by default and
    the port deflates through zlib, so the framed bytes differ for a reason that is not the tool's
    logic -- the same reason `--COMPRESSION_LEVEL` is excluded from every array, and the same pin
    htsjdk-rs asserts in a suite of its own (decisions 0001 and 0029). What is left after the
    decompression is the header and the records, which is what this array is measuring.
    """
    produced = out_dir / "output.txt"
    if not produced.exists():
        return ""
    raw = produced.read_bytes()
    try:
        return raw.decode("utf-8")
    except UnicodeDecodeError:
        pass
    payload, kind = decompressed(raw)
    if strip_program_records:
        payload = without_program_records(payload)
    return f"{kind} sha256={hashlib.sha256(payload).hexdigest()} bytes={len(payload)}"


def without_program_records(payload):
    """A BAM's bytes with the `@PG` lines removed from its header text.

    A tool that stamps its own provenance writes a `CL:` holding the command line it was given --
    temporary directories, argument order, the reference's version string. None of that is
    reproducible by a second implementation and none of it is the tool's answer, which is why the
    metrics suites canonicalize the same thing out of their text headers.

    This is the binary equivalent, and it is deliberately narrow: only the `@PG` LINES go, the
    header's length prefix is rewritten to match, and every other byte -- `@HD`, `@SQ`, `@RG`, and
    every record -- is hashed as it was. A tool whose `@PG` this hides a real difference in would
    have to differ in nothing else at all.
    """
    if len(payload) < 12 or payload[:4] != b"BAM\x01":
        return payload
    length = int.from_bytes(payload[4:8], "little")
    text = payload[8 : 8 + length].decode("utf-8", errors="replace")
    kept = "".join(line + "\n" for line in text.splitlines() if not line.startswith("@PG"))
    encoded = kept.encode("utf-8")
    return payload[:4] + len(encoded).to_bytes(4, "little") + encoded + payload[8 + length :]


def decompressed(raw):
    """A BGZF file's own bytes, and what the digest is therefore of."""
    if not raw.startswith(b"\x1f\x8b"):
        return raw, "BINARY"
    plain = bytearray()
    position = 0
    while position < len(raw):
        stream = zlib.decompressobj(31)
        plain += stream.decompress(raw[position:])
        remaining = len(stream.unused_data)
        if remaining == 0:
            break
        position = len(raw) - remaining
    return bytes(plain), "BGZF-CONTENT"


def first_error(text):
    """The reference's own error line.

    A rejected row is not a failed run: the reference rejects `FLOW_MODE=true` ("obsolete. Flow
    support now provided by CollectQualityYieldMetricsFlow") and rejects a queryname-sorted input
    unless ASSUME_SORTED is set. Both are behaviour the port has to reproduce, message included,
    so the message is recorded as this row's output rather than thrown away as noise.
    """
    # A Barclay validation failure prints the tool's entire usage first and its own message last,
    # and the usage is documentation: `RevertSam`'s help contains the sentence "the program will
    # exit with an Exception instead of exiting cleanly", which the scan below matched, so the row
    # recorded a doc line instead of the refusal. For a usage dump the refusal is the block after
    # the last blank line, which is where Barclay prints it.
    if text.lstrip().startswith("USAGE:"):
        tail = text.rstrip().split("\n\n")[-1].strip()
        if tail:
            return " ".join(line.strip() for line in tail.split("\n"))[:400]
    for line in text.split("\n"):
        if "Exception" in line or line.startswith("ERROR"):
            return line.strip()
    return text.strip().split("\n")[-1][:200] if text.strip() else ""


def run_port(binary, row_args, workdir, on_stdout=False, strip_pg=False):
    """Run the port binary on the same row, with the fixture paths rewritten to the host."""
    out_dir = fresh_directory(workdir, "port")

    rewritten = []
    for pair in row_args:
        name, _, value = pair.partition("=")
        value = value.replace("/work/fixtures", str(workdir / "fixtures"))
        value = value.replace("/work/out", str(out_dir))
        rewritten.append(f"{name}={value}")

    # The current binaries take `NAME=value` (the legacy form) and were written for the benchmark;
    # the Barclay command line is a later slice. Passing both forms keeps this working when it
    # lands, without pretending the binary understands more than it does.
    argv = [str(binary)] + [a.lstrip("-") for a in rewritten]
    result = subprocess.run(argv, capture_output=True, text=True)
    message = first_error(result.stderr or result.stdout)
    # The port ran against host paths because that is where the fixtures were mounted, so a
    # refusal that names its input names a path the reference could never print. MergeSamFiles is
    # the first tool to reproduce one ("Merging with interval but file is not indexed: <file>"),
    # and without this the row could not match however right the port was. Mapping the two mount
    # points back is the inverse of the rewrite above, not a canonicalization of the message: any
    # other difference in it still fails the row.
    message = message.replace(str(workdir / "fixtures"), "/work/fixtures")
    message = message.replace(str(out_dir), "/work/out")
    text = result.stdout if on_stdout else read_output(out_dir, strip_pg)
    # The same inverse on the OUTPUT, for the same reason and no other: a tool that writes a path it
    # was given writes the one it was given. `CreateSequenceDictionary` puts the reference's own
    # `file:` URI in every `@SQ` line's `UR`, so the port's rows differed from the reference's on
    # the mount point this harness chose and on nothing else. Undoing the rewrite is not a
    # canonicalization of the tool's answer: it is the inverse of what the runner did on the way in,
    # and any other difference in the text still fails the row.
    if isinstance(text, str):
        text = text.replace(str(workdir / "fixtures"), "/work/fixtures")
        text = text.replace(str(out_dir), "/work/out")
    return result.returncode, text, message


def outcome(code, text, error, tool):
    """One row's result, as the thing that will be compared: output, or rejection."""
    if code != 0:
        return f"EXIT={code} {error}"
    if not text:
        return ""
    # A digest is already canonical, and running it through the metrics stripper would only put a
    # header prefix through a hash that has none.
    if text.startswith("BINARY sha256=") or text.startswith("BGZF-CONTENT sha256="):
        return text
    return canonical(text, tool)


def canonical(text, tool):
    """Strip the two lines every metrics file carries that no two runs can share."""
    spec = {
        "rules": [
            {"rule": "strip_line_prefixes", "prefixes": [f"# {tool}", "# Started on:"]}
        ]
    }
    payload = "\\n".join(text.split("\n"))
    return comparator.canonicalize("output", payload, spec["rules"])


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--tool", required=True)
    ap.add_argument("--t", type=int, default=2)
    ap.add_argument("--port", help="path to the port binary; omit to run the oracle alone")
    ap.add_argument("--dump", help="write the corpus here (default tools/coverage/corpus/<tool>.txt)")
    ap.add_argument("--limit", type=int, help="run only the first N rows")
    ap.add_argument(
        "--strip-program-records",
        action="store_true",
        help="hash a BAM output with its @PG lines removed, for a tool that stamps its own "
        "provenance with the command line it was given",
    )
    ap.add_argument(
        "--stdout",
        action="store_true",
        help="compare standard output rather than the output file, for a tool that writes no file",
    )
    args = ap.parse_args(argv)

    array_path = ARRAYS / f"{args.tool}.t{args.t}.json"
    if not array_path.exists():
        raise SystemExit(
            f"no array at {array_path}. Generate it in gatk-rs with:\n"
            f"  python3 tools/coverage/covering.py --tool {args.tool} --t {args.t} \\\n"
            f"    --fixtures <this repo>/tools/coverage/fixtures.json --json {array_path}"
        )
    array = json.load(open(array_path))
    rows = array["array"][: args.limit]

    workdir = Path(tempfile.mkdtemp(prefix="covering-"))
    try:
        print(f"building fixtures in {workdir}")
        build_fixtures(workdir)

        results = []
        for row in rows:
            row_args = row_arguments(row, array["excluded"])
            code, text, tail = run_oracle(
                args.tool, row_args, workdir, args.stdout, args.strip_program_records
            )
            entry = {
                "row": row["row"],
                "labels": row["labels"],
                "arguments": row_args,
                "oracle_exit": code,
                "oracle_output": outcome(code, text, tail, args.tool),
                "oracle_error": "" if code == 0 else tail,
            }
            if args.port:
                p_code, p_text, p_tail = run_port(
                    args.port, row_args, workdir, args.stdout, args.strip_program_records
                )
                entry["port_exit"] = p_code
                entry["port_output"] = outcome(p_code, p_text, p_tail, args.tool)
                entry["port_error"] = "" if p_code == 0 else p_tail
                # Reproducing a rejection is reproducing the tool: a row both sides reject with
                # the same message is a match, not a skipped case.
                entry["match"] = (
                    code == p_code and entry["oracle_output"] == entry["port_output"]
                )
            results.append(entry)
            state = "ok " if code == 0 else f"rejected ({code})"
            extra = ""
            if args.port:
                extra = "  port=" + ("match" if entry["match"] else "DIFFERS")
            print(f"row {row['row']:>3} {state}{extra}")

        accepted = [r for r in results if r["oracle_exit"] == 0]
        distinct = {r["oracle_output"] for r in accepted}
        rejections = {r["oracle_output"] for r in results if r["oracle_exit"] != 0}
        print(
            f"\n{args.tool}: rows={len(results)} accepted by the reference={len(accepted)} "
            f"rejected={len(results) - len(accepted)} distinct outputs={len(distinct)} "
            f"distinct rejections={len(rejections)}"
        )
        for message in sorted(rejections):
            print(f"  rejection: {message[:150]}")
        if len(distinct) == 1 and len(accepted) > 1:
            print(
                "  every accepted row produced the same output: on this corpus the varied "
                "arguments are unobservable, so the array covers them without testing them"
            )
        if args.port:
            matched = sum(1 for r in results if r.get("match"))
            print(
                f"  port matches the reference on {matched}/{len(results)} rows "
                f"({matched / len(results):.0%} of the pairwise surface)"
            )

        dump_path = Path(args.dump) if args.dump else (
            REPO / "tools" / "coverage" / "corpus" / f"{args.tool}.t{args.t}.txt"
        )
        dump_path.parent.mkdir(parents=True, exist_ok=True)
        with open(dump_path, "w") as fh:
            fh.write(f"# {args.tool} t={args.t} rows={len(results)} from {array_path.name}\n")
            for entry in results:
                labels = ",".join(f"{k.lstrip('-')}={v}" for k, v in sorted(entry["labels"].items()))
                fh.write(f"row\t{entry['row']}:{labels}\t{entry['oracle_output']}\n")
                # A mismatching row records what the port answered too. A coverage figure with no
                # such rows behind it is a number nobody can check, and the first run of this
                # measurement produced 0% on both tools: the artefact has to say what 0% means.
                if args.port and not entry["match"]:
                    fh.write(f"port\t{entry['row']}:{labels}\t{entry['port_output']}\n")
        print(f"wrote {dump_path}")
        return 0
    finally:
        shutil.rmtree(workdir, ignore_errors=True)


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
